function S=frame_first_stable_pick(B,C)
% Input is frame_stable_runs' classified copy, not locally_stable candidates.
assert(isnumeric(C.firstStableSeconds) && isscalar(C.firstStableSeconds) && ...
 isfinite(C.firstStableSeconds) && C.firstStableSeconds>=0 && ...
 C.firstStableSeconds==fix(C.firstStableSeconds), ...
 'Frame:Selection','firstStableSeconds must be a nonnegative integer.');
assert(isnumeric(C.minimumStableSeconds) && isscalar(C.minimumStableSeconds) && ...
 isfinite(C.minimumStableSeconds) && C.minimumStableSeconds>=1 && ...
 C.minimumStableSeconds==fix(C.minimumStableSeconds), ...
 'Frame:Selection','minimumStableSeconds must be a positive integer.');
assert(C.firstStableSeconds==0 || (isempty(C.analysisIntervalS) && ...
 C.minimumStableSeconds<=C.firstStableSeconds), ...
 'Frame:Selection','Use firstStableSeconds OR analysisIntervalS; minimum must not exceed target.');
S=struct('mode',"first_stable",'target',C.firstStableSeconds, ...
 'minimum',C.minimumStableSeconds,'found',0,'report_seconds',[], ...
 'reached_target',false,'eligible',false,'last_needed_index',numel(B));
if isempty(B) || C.firstStableSeconds==0, return; end
ix=find(string({B.status})=="accepted");
[~,order]=sort([B(ix).second]); ix=ix(order);
S.found=numel(ix); ix=ix(1:min(numel(ix),C.firstStableSeconds));
S.report_seconds=[B(ix).second];
S.reached_target=numel(ix)>=C.firstStableSeconds;
S.eligible=numel(ix)>=C.minimumStableSeconds;
if S.reached_target
 % One halo for overlap windows, another for those windows' own IQ context.
 % Default .4 s context -> at most two additional synchronized seconds.
 halo=ceil(C.decodeContextS+C.matchToleranceS+C.boundaryGuardS+.01);
 rightPadding=halo+ceil(C.decodeContextS);
 S.last_needed_index=min(numel(B),ix(end)+rightPadding);
end
end
